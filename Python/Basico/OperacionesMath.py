"""Operaciones matematicas con Python
Python nos permite realizar las siguientes operaciones matemáticas
A continuación presentamos cada una con su operador respectivo:

Suma +
Resta -
Multiplicación *
División /
División entera //
Modulo (resto) %
Potenciación **"""

num1 = 150
num2 = 200
num3 = 1035
num4 = 100
resultadoSuma = num1 + num2
resultadoResta = num2 - num1
resultadoMultiplicacion = num1 * num2
resultadoDivision = num3 / num4
resultadoDivexacta = num3 // num4
resultadoResto = num3 % num4
resultadoPotencia = num4 ** 2
print("Resultado suma",resultadoSuma)
print("Resultado resta",resultadoResta)
print("Resultado Multiplicación", resultadoMultiplicacion)
print("Resultado División", resultadoDivision)
print("Resultado Division Exacta", resultadoDivexacta)
print("Resultado del Resto", resultadoResto)
print("Resultado Potencia", resultadoPotencia)
